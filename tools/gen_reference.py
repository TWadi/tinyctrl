#!/usr/bin/env python3
"""Generates the reference data used by the tinyctrl unit tests with SciPy.

This is the SciPy counterpart of tools/gen_reference.m and writes the same file,
tests/reference/reference_data.h. Every expected value comes from scipy.signal (bilinear, lfilter), an
implementation independent of tinyctrl. Run from the repository root:

    python tools/gen_reference.py

SPDX-License-Identifier: MIT
"""
import math
from pathlib import Path

import numpy as np
import scipy
from scipy import signal

OUT_PATH = Path("tests") / "reference" / "reference_data.h"


def fmt(value):
    return repr(float(value))


def join_nums(values):
    return ", ".join(fmt(v) for v in values)


def write_array(lines, name, values):
    lines.append(f"static const double {name}[{len(values)}] = {{")
    lines.extend(f"    {fmt(v)}," for v in values)
    lines.append("};")
    lines.append("")


def trim_leading(poly):
    poly = list(poly)
    while len(poly) > 1 and poly[0] == 0:
        poly.pop(0)
    return poly


def tustin(num, den, ts, prewarp):
    """Tustin discretisation; prewarping at w is bilinear() with fs = w / (2 tan(w Ts / 2))."""
    fs = prewarp / (2.0 * math.tan(prewarp * ts / 2.0)) if prewarp > 0 else 1.0 / ts
    b, a = signal.bilinear(trim_leading(num), trim_leading(den), fs=fs)
    b = np.atleast_1d(b) / a[0]
    a = np.atleast_1d(a) / a[0]
    # bilinear() pads the shorter polynomial; strip the common padding of lower-order systems.
    order = len(trim_leading(den)) - 1
    b = np.concatenate([b[-(order + 1):], np.zeros(2 - order)])
    a = np.concatenate([a[-(order + 1):], np.zeros(2 - order)])
    return b, a


def main():
    n = 200
    k = np.arange(n)
    x = (np.sin(2 * np.pi * 0.013 * k) + 0.5 * np.sin(2 * np.pi * 0.11 * k + 0.3)
         + (k >= 50).astype(float) - 0.7 * (k >= 120).astype(float))

    lines = [
        f"/* Generated by tools/gen_reference.py with SciPy {scipy.__version__}. Do not edit. */",
        "/* SPDX-License-Identifier: MIT */",
        "#ifndef TINYCTRL_REFERENCE_DATA_H",
        "#define TINYCTRL_REFERENCE_DATA_H",
        "",
        f"#define REF_N {n}",
        "",
    ]
    write_array(lines, "ref_input", x)

    wn = 2 * np.pi * 50
    zeta = 0.7
    wnotch = 2 * np.pi * 100
    q = 5
    cases = [
        # num (s^2 s^1 s^0)        den (s^2 s^1 s^0)             Ts      prewarp [rad/s]
        ([0, 0, wn ** 2], [1, 2 * zeta * wn, wn ** 2], 1e-3, 0.0),
        ([0, 0, wn ** 2], [1, 2 * zeta * wn, wn ** 2], 1e-3, wn),
        ([1, 0, wnotch ** 2], [1, wnotch / q, wnotch ** 2], 0.5e-3, wnotch),
        ([0, 1 / 10, 1], [0, 1 / 100, 1], 1e-3, 0.0),
        ([0, 2, 5], [0, 1, 0], 1e-2, 0.0),
        ([0, 0, 3], [0, 0, 2], 1e-2, 0.0),
    ]
    lines += [
        "typedef struct",
        "{",
        "    double num[3];",
        "    double den[3];",
        "    double ts;",
        "    double prewarp;",
        "    double b0, b1, b2, a1, a2;",
        "} ref_tustin_case;",
        "",
        "static const ref_tustin_case ref_tustin_cases[] = {",
    ]
    notch = None
    for i, (num, den, ts, w) in enumerate(cases):
        b, a = tustin(num, den, ts, w)
        lines.append(f"    {{{{{join_nums(num)}}}, {{{join_nums(den)}}}, {fmt(ts)}, {fmt(w)}, "
                     f"{fmt(b[0])}, {fmt(b[1])}, {fmt(b[2])}, {fmt(a[1])}, {fmt(a[2])}}},")
        if i == 2:
            notch = (b, a)
    lines.append("};")
    lines.append(f"#define REF_TUSTIN_COUNT {len(cases)}")
    lines.append("")

    write_array(lines, "ref_biquad_notch_output", signal.lfilter(notch[0], notch[1], x))

    # PID with setpoint 0 and measurement x: u = -C(z) x, C(s) = Kp + Ki / s + Kd s / (Tf s + 1).
    pids = [
        # Kp   Ki    Kd   Tf    Ts
        (2.0, 5.0, 0.1, 0.01, 1e-3),
        (1.5, 20.0, 0.0, 0.0, 1e-2),
    ]
    for i, (kp, ki, kd, tf, ts) in enumerate(pids, start=1):
        num = [kp * tf + kd, kp + ki * tf, ki]  # over the common denominator s (Tf s + 1)
        den = [tf, 1.0, 0.0]
        b, a = signal.bilinear(trim_leading(num), trim_leading(den), fs=1.0 / ts)
        u = signal.lfilter(-np.asarray(b), a, x)
        lines.append(f"/* PID {i}: Kp = {kp:g}, Ki = {ki:g}, Kd = {kd:g}, Tf = {tf:g}, Ts = {ts:g} */")
        lines.append(f"static const double ref_pid{i}_params[5] = {{{join_nums([kp, ki, kd, tf, ts])}}};")
        write_array(lines, f"ref_pid{i}_output", u)

    tau, ts = 0.05, 0.01
    alpha = -math.expm1(-ts / tau)
    lines.append(f"static const double ref_lowpass_params[2] = {{{join_nums([tau, ts])}}}; /* tau, Ts */")
    write_array(lines, "ref_lowpass_output", signal.lfilter([alpha], [1.0, alpha - 1.0], x))

    leadlags = [
        # gain  wz   wp     Ts
        (2.0, 10.0, 100.0, 1e-3),  # lead
        (5.0, 1.0, 0.1, 1e-2),  # lag
    ]
    for i, (gain, wz, wp, ts) in enumerate(leadlags, start=1):
        b, a = signal.bilinear([gain / wz, gain], [1.0 / wp, 1.0], fs=1.0 / ts)
        lines.append(f"static const double ref_leadlag{i}_params[4] = {{{join_nums([gain, wz, wp, ts])}}}; "
                     "/* gain, wz, wp, Ts */")
        write_array(lines, f"ref_leadlag{i}_output", signal.lfilter(b, a, x))

    lines.append("#endif /* TINYCTRL_REFERENCE_DATA_H */")
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
