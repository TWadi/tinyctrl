% gen_reference.m - Generates the reference data used by the tinyctrl unit tests.
%
% Every expected value comes from MATLAB and the Control System Toolbox (c2d, pid, filter), so the tests
% check tinyctrl against an independent implementation. Run from the repository root:
%
%     matlab -batch "run('tools/gen_reference.m')"
%
% The output, tests/reference/reference_data.h, is committed so that building the tests does not need MATLAB.
%
% SPDX-License-Identifier: MIT

outPath = fullfile('tests', 'reference', 'reference_data.h');
fid = fopen(outPath, 'w');
assert(fid > 0, 'cannot open %s', outPath);
closer = onCleanup(@() fclose(fid));

v = ver('MATLAB');
fprintf(fid, '/* Generated by tools/gen_reference.m with MATLAB %s %s. Do not edit. */\n', v.Version, v.Release);
fprintf(fid, '/* SPDX-License-Identifier: MIT */\n');
fprintf(fid, '#ifndef TINYCTRL_REFERENCE_DATA_H\n#define TINYCTRL_REFERENCE_DATA_H\n\n');

%% Input signal shared by the time-domain tests: two sines plus two steps.
N = 200;
k = (0:N - 1)';
x = sin(2 * pi * 0.013 * k) + 0.5 * sin(2 * pi * 0.11 * k + 0.3) + (k >= 50) - 0.7 * (k >= 120);
fprintf(fid, '#define REF_N %d\n\n', N);
writeArray(fid, 'ref_input', x);

%% tc_tustin: c2d(tf(num, den), Ts, 'tustin'), optionally prewarped.
wn = 2 * pi * 50; zeta = 0.7;
wnotch = 2 * pi * 100; q = 5;
cases = {
    % num (s^2 s^1 s^0)     den (s^2 s^1 s^0)              Ts       prewarp [rad/s]
    [0 0 wn^2],             [1 2 * zeta * wn wn^2],         1e-3,    0
    [0 0 wn^2],             [1 2 * zeta * wn wn^2],         1e-3,    wn
    [1 0 wnotch^2],         [1 wnotch / q wnotch^2],        0.5e-3,  wnotch
    [0 1 / 10 1],           [0 1 / 100 1],                  1e-3,    0
    [0 2 5],                [0 1 0],                        1e-2,    0
    [0 0 3],                [0 0 2],                        1e-2,    0
};
fprintf(fid, 'typedef struct\n{\n    double num[3];\n    double den[3];\n    double ts;\n    double prewarp;\n');
fprintf(fid, '    double b0, b1, b2, a1, a2;\n} ref_tustin_case;\n\n');
fprintf(fid, 'static const ref_tustin_case ref_tustin_cases[] = {\n');
for i = 1:size(cases, 1)
    [num, den, ts, w] = cases{i, :};
    sysc = tf(trimLeading(num), trimLeading(den));
    if w > 0
        sysd = c2d(sysc, ts, c2dOptions('Method', 'tustin', 'PrewarpFrequency', w));
    else
        sysd = c2d(sysc, ts, 'tustin');
    end
    [b, a] = biquadCoeffs(sysd);
    fprintf(fid, '    {{%s}, {%s}, %.17g, %.17g, %.17g, %.17g, %.17g, %.17g, %.17g},\n', ...
        joinNums(num), joinNums(den), ts, w, b(1), b(2), b(3), a(2), a(3));
    if i == 3
        notchB = b; notchA = a; % reused for the biquad time-domain test
    end
end
fprintf(fid, '};\n#define REF_TUSTIN_COUNT %d\n\n', size(cases, 1));

%% tc_biquad: filter() with the notch coefficients from case 3.
writeArray(fid, 'ref_biquad_notch_output', filter(notchB, notchA, x));

%% tc_pid: setpoint 0 and measurement x, so u = -C(z) x with C = c2d(pid(Kp, Ki, Kd, Tf), Ts, 'tustin').
pids = {
    % Kp   Ki   Kd    Tf     Ts
    2.0,  5.0, 0.1,  0.01,  1e-3
    1.5, 20.0, 0.0,  0.0,   1e-2
};
for i = 1:size(pids, 1)
    [kp, ki, kd, tfilt, ts] = pids{i, :};
    cd = c2d(tf(pid(kp, ki, kd, tfilt)), ts, 'tustin');
    [b, a] = tfdata(-cd, 'v');
    u = filter(b, a, x);
    fprintf(fid, '/* PID %d: Kp = %g, Ki = %g, Kd = %g, Tf = %g, Ts = %g */\n', i, kp, ki, kd, tfilt, ts);
    fprintf(fid, 'static const double ref_pid%d_params[5] = {%s};\n', i, joinNums([kp ki kd tfilt ts]));
    writeArray(fid, sprintf('ref_pid%d_output', i), u);
end

%% tc_lowpass: alpha = 1 - exp(-Ts / tau), y[k] = (1 - alpha) y[k-1] + alpha x[k], zero initial state.
tau = 0.05; ts = 0.01;
alpha = 1 - exp(-ts / tau);
fprintf(fid, 'static const double ref_lowpass_params[2] = {%s}; /* tau, Ts */\n', joinNums([tau ts]));
writeArray(fid, 'ref_lowpass_output', filter(alpha, [1, alpha - 1], x));

%% tc_leadlag: c2d(gain * tf([1/wz 1], [1/wp 1]), Ts, 'tustin').
leadlags = {
    % gain  wz    wp     Ts
    2.0,   10,   100,   1e-3   % lead
    5.0,   1,    0.1,   1e-2   % lag
};
for i = 1:size(leadlags, 1)
    [gain, wz, wp, ts] = leadlags{i, :};
    cd = c2d(gain * tf([1 / wz 1], [1 / wp 1]), ts, 'tustin');
    [b, a] = tfdata(cd, 'v');
    fprintf(fid, 'static const double ref_leadlag%d_params[4] = {%s}; /* gain, wz, wp, Ts */\n', i, ...
        joinNums([gain wz wp ts]));
    writeArray(fid, sprintf('ref_leadlag%d_output', i), filter(b, a, x));
end

fprintf(fid, '#endif /* TINYCTRL_REFERENCE_DATA_H */\n');
fprintf('Wrote %s\n', outPath);

%% Helpers
function writeArray(fid, name, values)
    fprintf(fid, 'static const double %s[%d] = {\n', name, numel(values));
    for j = 1:numel(values)
        fprintf(fid, '    %.17g,\n', values(j));
    end
    fprintf(fid, '};\n\n');
end

function s = joinNums(values)
    s = strjoin(arrayfun(@(val) sprintf('%.17g', val), values, 'UniformOutput', false), ', ');
end

function p = trimLeading(p)
    % tf() wants polynomials without leading zeros; keep at least one coefficient.
    first = find(p ~= 0, 1);
    if isempty(first)
        p = 0;
    else
        p = p(first:end);
    end
end

function [b, a] = biquadCoeffs(sysd)
    % Normalised [b0 b1 b2] and [1 a1 a2] in powers of z^-1, padded with zeros for lower orders.
    [num, den] = tfdata(sysd, 'v');
    b = num / den(1);
    a = den / den(1);
    b = [b, zeros(1, 3 - numel(b))];
    a = [a, zeros(1, 3 - numel(a))];
end
